"""
Retention Campaign Financial ROI Simulator.

Calculates expected financial returns, cost-benefit trade-offs, break-even thresholds,
and policy comparisons for telecom customer retention campaigns.
"""

from pathlib import Path
from typing import Dict, Any, List, Optional
import json
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt


PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent
FIGURES_DIR = PROJECT_ROOT / "reports" / "figures"
MODELS_DIR = PROJECT_ROOT / "models"


def calculate_discounted_customer_value(
    monthly_arpu: float,
    gross_margin: float = 0.70,
    horizon_months: int = 12,
    annual_discount_rate: float = 0.10,
) -> float:
    """
    Computes the Net Present Value (NPV) of gross profit generated by a single retained customer
    over a designated time horizon.
    """
    monthly_discount_rate = (1.0 + annual_discount_rate) ** (1.0 / 12.0) - 1.0
    monthly_profit = monthly_arpu * gross_margin

    t_months = np.arange(1, horizon_months + 1)
    discount_factors = 1.0 / ((1.0 + monthly_discount_rate) ** t_months)
    npv_value = float(np.sum(monthly_profit * discount_factors))

    return round(npv_value, 2)


def simulate_retention_campaign(
    target_population: int,
    offer_cost: float,
    baseline_churn_rate: float,
    retention_uplift: float,
    customer_arpu: float,
    gross_margin: float = 0.70,
    horizon_months: int = 12,
    annual_discount_rate: float = 0.10,
) -> Dict[str, Any]:
    """
    Simulates the financial P&L and ROI of a targeted retention campaign.

    Args:
        target_population: Number of customers targeted with retention offer.
        offer_cost: Per-customer cost of retention incentive (e.g., $30 bill credit / hardware upgrade).
        baseline_churn_rate: Expected churn rate without intervention (0.0 to 1.0).
        retention_uplift: Absolute percentage point reduction in churn caused by offer (e.g., 0.12).
        customer_arpu: Average Monthly Revenue per User ($).
        gross_margin: Gross profit margin (0.0 to 1.0).
        horizon_months: Evaluation horizon in months.
        annual_discount_rate: Annual corporate cost of capital (WACC).

    Returns:
        Dict containing comprehensive financial outputs and ROI metrics.
    """
    if target_population <= 0:
        raise ValueError("target_population must be strictly positive.")
    if offer_cost < 0:
        raise ValueError("offer_cost cannot be negative.")
    if not (0.0 <= baseline_churn_rate <= 1.0):
        raise ValueError("baseline_churn_rate must be between 0.0 and 1.0.")
    if retention_uplift < 0:
        raise ValueError("retention_uplift cannot be negative.")

    # Bound effective uplift so it cannot exceed baseline churn
    effective_uplift = min(retention_uplift, baseline_churn_rate)

    # 1. Volume metrics
    expected_natural_churners = int(round(target_population * baseline_churn_rate))
    incrementally_saved_customers = int(round(target_population * effective_uplift))
    post_campaign_churners = max(0, expected_natural_churners - incrementally_saved_customers)
    post_campaign_churn_rate = post_campaign_churners / target_population if target_population > 0 else 0.0

    # 2. Financial metrics
    total_campaign_cost = target_population * offer_cost
    npv_retained_value_per_customer = calculate_discounted_customer_value(
        monthly_arpu=customer_arpu,
        gross_margin=gross_margin,
        horizon_months=horizon_months,
        annual_discount_rate=annual_discount_rate,
    )

    gross_financial_benefit = incrementally_saved_customers * npv_retained_value_per_customer
    net_profit = gross_financial_benefit - total_campaign_cost

    roi_percentage = (net_profit / total_campaign_cost * 100.0) if total_campaign_cost > 0 else 0.0

    # 3. Break-even analysis
    # Break-even uplift is the minimum uplift required to cover total campaign cost:
    # saved_cust * npv_per_cust >= pop * offer_cost  =>  (pop * be_uplift) * npv >= pop * offer_cost
    # => be_uplift = offer_cost / npv_retained_value_per_customer
    break_even_uplift = offer_cost / npv_retained_value_per_customer if npv_retained_value_per_customer > 0 else 1.0
    break_even_saved_customers = int(np.ceil(total_campaign_cost / npv_retained_value_per_customer)) if npv_retained_value_per_customer > 0 else target_population

    return {
        "inputs": {
            "target_population": target_population,
            "offer_cost_per_customer": offer_cost,
            "baseline_churn_rate": baseline_churn_rate,
            "retention_uplift": retention_uplift,
            "effective_uplift": round(effective_uplift, 4),
            "customer_arpu": customer_arpu,
            "gross_margin": gross_margin,
            "horizon_months": horizon_months,
            "annual_discount_rate": annual_discount_rate,
        },
        "volume_outcomes": {
            "expected_natural_churners": expected_natural_churners,
            "incrementally_saved_customers": incrementally_saved_customers,
            "post_campaign_churners": post_campaign_churners,
            "post_campaign_churn_rate": round(post_campaign_churn_rate, 4),
        },
        "financial_outcomes": {
            "total_campaign_cost": round(total_campaign_cost, 2),
            "npv_value_per_saved_customer": npv_retained_value_per_customer,
            "gross_financial_benefit": round(gross_financial_benefit, 2),
            "net_campaign_profit": round(net_profit, 2),
            "roi_percentage": round(roi_percentage, 2),
            "cost_per_saved_customer": round(total_campaign_cost / incrementally_saved_customers, 2) if incrementally_saved_customers > 0 else None,
        },
        "break_even": {
            "break_even_uplift_pct": round(break_even_uplift * 100.0, 2),
            "break_even_saved_customers": break_even_saved_customers,
            "is_profitable": bool(net_profit > 0),
        },
    }


def compare_retention_policies() -> pd.DataFrame:
    """
    Compares 3 retention targeting policies for IBM Telco portfolio:
    1. Mass Blanket Policy: Target all 7,043 customers indiscriminately.
    2. Churn Risk-Only Policy: Target all high-risk accounts (prob >= 0.28).
    3. Precision Policy: Target only high-value, high-risk, persuadable accounts
       (Vulnerable High-Spenders + Persuadables).
    """
    # Policy 1: Mass Blanket (All 7,043 customers, offer cost $25, baseline churn 26.54%, low average uplift 3%)
    p1 = simulate_retention_campaign(
        target_population=7043,
        offer_cost=25.0,
        baseline_churn_rate=0.2654,
        retention_uplift=0.03,
        customer_arpu=64.76,  # Portfolio average ARPU
        horizon_months=12,
    )

    # Policy 2: Risk-Only (Target predicted churners ~ 2,300 accounts, offer cost $35, baseline churn 65%, uplift 6%)
    p2 = simulate_retention_campaign(
        target_population=2300,
        offer_cost=35.0,
        baseline_churn_rate=0.65,
        retention_uplift=0.06,
        customer_arpu=74.44,  # Churner average ARPU
        horizon_months=12,
    )

    # Policy 3: Precision Policy (Target Vulnerable High-Spenders who are Persuadable ~ 1,200 accounts,
    # premium offer $45, baseline churn 63%, high uplift 12%, ARPU $85.22)
    p3 = simulate_retention_campaign(
        target_population=1200,
        offer_cost=45.0,
        baseline_churn_rate=0.63,
        retention_uplift=0.12,
        customer_arpu=85.22,  # Vulnerable High-Spender ARPU
        horizon_months=12,
    )

    policies = [
        {
            "Policy": "1. Mass Blanket (Untargeted)",
            "Targeted Accounts": p1["inputs"]["target_population"],
            "Offer Cost": f"${p1['inputs']['offer_cost_per_customer']:.0f}",
            "Total Cost": f"${p1['financial_outcomes']['total_campaign_cost']:,.0f}",
            "Saved Customers": p1["volume_outcomes"]["incrementally_saved_customers"],
            "Gross Benefit": f"${p1['financial_outcomes']['gross_financial_benefit']:,.0f}",
            "Net Profit": f"${p1['financial_outcomes']['net_campaign_profit']:,.0f}",
            "ROI (%)": f"{p1['financial_outcomes']['roi_percentage']:.1f}%",
        },
        {
            "Policy": "2. Risk-Only (All Prob >= 0.28)",
            "Targeted Accounts": p2["inputs"]["target_population"],
            "Offer Cost": f"${p2['inputs']['offer_cost_per_customer']:.0f}",
            "Total Cost": f"${p2['financial_outcomes']['total_campaign_cost']:,.0f}",
            "Saved Customers": p2["volume_outcomes"]["incrementally_saved_customers"],
            "Gross Benefit": f"${p2['financial_outcomes']['gross_financial_benefit']:,.0f}",
            "Net Profit": f"${p2['financial_outcomes']['net_campaign_profit']:,.0f}",
            "ROI (%)": f"{p2['financial_outcomes']['roi_percentage']:.1f}%",
        },
        {
            "Policy": "3. Precision (High-CLV Persuadables)",
            "Targeted Accounts": p3["inputs"]["target_population"],
            "Offer Cost": f"${p3['inputs']['offer_cost_per_customer']:.0f}",
            "Total Cost": f"${p3['financial_outcomes']['total_campaign_cost']:,.0f}",
            "Saved Customers": p3["volume_outcomes"]["incrementally_saved_customers"],
            "Gross Benefit": f"${p3['financial_outcomes']['gross_financial_benefit']:,.0f}",
            "Net Profit": f"${p3['financial_outcomes']['net_campaign_profit']:,.0f}",
            "ROI (%)": f"{p3['financial_outcomes']['roi_percentage']:.1f}%",
        },
    ]

    return pd.DataFrame(policies)


def plot_roi_simulation_curves(output_dir: Path = FIGURES_DIR):
    """
    Generates Figure 26: Sensitivity curve of Net Campaign Profit across various offer costs and uplifts.
    """
    output_dir.mkdir(parents=True, exist_ok=True)

    uplifts = np.linspace(0.02, 0.20, 100)
    offer_costs = [25.0, 40.0, 60.0]
    colors = ["#10B981", "#3B82F6", "#EF4444"]

    plt.figure(figsize=(9, 5.5), dpi=300)

    for cost, color in zip(offer_costs, colors):
        profits = []
        for up in uplifts:
            sim = simulate_retention_campaign(
                target_population=1000,
                offer_cost=cost,
                baseline_churn_rate=0.60,
                retention_uplift=up,
                customer_arpu=85.0,
                horizon_months=12,
            )
            profits.append(sim["financial_outcomes"]["net_campaign_profit"])

        plt.plot(
            uplifts * 100,
            profits,
            linewidth=2.2,
            color=color,
            label=f"Offer Cost: ${cost:.0f}/customer",
        )

    plt.axhline(0, color="black", linestyle="--", linewidth=1.2, alpha=0.7, label="Break-Even Line ($0 Profit)")
    plt.title("Figure 26: Retention Campaign Net Profit Sensitivity (1,000 High-Value Accounts)", fontsize=13, fontweight="bold", pad=12)
    plt.xlabel("Retention Uplift (% pts Churn Reduction)", fontsize=11)
    plt.ylabel("Net Campaign Profit ($)", fontsize=11)
    plt.grid(True, linestyle="--", alpha=0.5)
    plt.legend(frameon=True, facecolor="white")
    plt.tight_layout()
    plt.savefig(output_dir / "26_roi_sensitivity_curves.png")
    plt.close()


def run_and_save_roi_analysis():
    print("=" * 65)
    print("Running Retention Campaign ROI Simulator & Policy Benchmark...")
    print("=" * 65)

    comparison_df = compare_retention_policies()
    print("\nTargeting Policy Financial Comparison:")
    print(comparison_df.to_string(index=False))

    plot_roi_simulation_curves()
    print(f"\nSaved Figure 26 to {FIGURES_DIR / '26_roi_sensitivity_curves.png'}")

    # Standard reference baseline simulation for JSON export
    reference_sim = simulate_retention_campaign(
        target_population=1200,
        offer_cost=45.0,
        baseline_churn_rate=0.63,
        retention_uplift=0.12,
        customer_arpu=85.22,
        horizon_months=12,
    )

    summary = {
        "reference_simulation": reference_sim,
        "policy_comparison": comparison_df.to_dict(orient="records"),
    }

    with open(MODELS_DIR / "roi_simulation_summary.json", "w") as f:
        json.dump(summary, f, indent=2)

    print(f"Saved ROI summary to {MODELS_DIR / 'roi_simulation_summary.json'}")


if __name__ == "__main__":
    run_and_save_roi_analysis()
